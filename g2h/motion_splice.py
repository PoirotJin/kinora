"""Two-clip splice: rigid ground-plane transforms plus a Kimodo-regenerated gap.

The service builds one intermediate motion: clip A (trimmed, turned and
moved), a smooth placeholder gap, then clip B. The gap is then regenerated by
the existing, verified Kimodo local edit (kimodo_edit.py), which freezes the
exterior bit-for-bit and constrains the last frames of A and the first frames
of B. The placeholder never reaches a user as a result: it is only the edit's
source, and every frame of it is replaced or blended inside the selection.

Convention (matches the desktop preview): Y up, ground plane X/Z. A clip turns
about the vertical axis through its root at its first kept frame. Positive
``turn_right_deg`` is clockwise seen from above (heading atan2(x, z) falls).
Only root position and root orientation change; body poses are untouched.
"""
from pathlib import Path

import numpy as np
from scipy.spatial.transform import Rotation, Slerp

from .motion_assets import STATIC, validate_motion

VERSION = 'motion-splice-v1'
PROMPT = ('A person walks naturally with relaxed, comfortable steps, smoothly turning toward the new '
          'direction, feet hip-width apart and arms swinging clear of the body.')
LIMITS = {'clips': 2, 'min_clip_frames': 12, 'min_transition_frames': 15, 'max_transition_frames': 540,
          'max_speed_m_s': 1.6, 'max_turn_deg_s': 120.0, 'fps': 30, 'max_turn_input_deg': 180.0,
          'max_offset_m': 100.0}
CANONICAL = ('native_keypoints3d', 'native_transl', 'smpl_poses', 'native_rot6d',
             'native_root_rotations_mat', 'smpl_trans', 'smpl_Rh')
L_HIP, R_HIP = 1, 2


PROJECT = Path(__file__).resolve().parents[1]


def rig(project=PROJECT):
    """Same farm compatibility rig the Kimodo worker composes with.

    It lives in the project tree, not in the service's data root.
    """
    folder = Path(project) / 'third_party/HY-Motion-1.0/scripts/gradio/static/assets/dump_wooden'
    rest = np.fromfile(folder / 'j_template.bin', dtype=np.float32).reshape(-1, 3).astype(np.float64)
    parents = np.fromfile(folder / 'kintree.bin', dtype=np.int32).copy()
    if rest.shape != (52, 3) or parents.shape != (52,):
        raise ValueError('缺少兼容的拼接骨架')
    parents[0] = -1
    return rest, parents


def _yaw(turn_right_deg):
    return Rotation.from_rotvec([0.0, -np.deg2rad(turn_right_deg), 0.0]).as_matrix()


def _frames(arrays):
    return len(arrays['native_transl'])


def _local(arrays):
    frames = _frames(arrays)
    return Rotation.from_rotvec(arrays['smpl_poses'].reshape(-1, 3).astype(np.float64)).as_matrix().reshape(frames, 52, 3, 3)


def _channels(arrays):
    frames = _frames(arrays)
    unknown = [k for k, v in arrays.items() if k not in CANONICAL and k not in STATIC
               and not k.startswith('kimodo_') and np.ndim(v) and np.shape(v)[0] == frames]
    if unknown:
        raise ValueError('无法拼接动作扩展字段：' + ', '.join(sorted(unknown)))
    return [k for k in CANONICAL if k in arrays]


def _fill(local, transl, keys, dtypes, rest, parents):
    """Derive every canonical channel from local rotations and root translation."""
    from .kimodo_adapter import fk
    frames = len(local)
    poses = Rotation.from_matrix(local.reshape(-1, 3, 3)).as_rotvec().reshape(frames, 156)
    points, _ = fk(local, rest, parents)
    values = {'native_keypoints3d': points, 'native_transl': transl, 'smpl_trans': transl,
              'smpl_poses': poses, 'smpl_Rh': poses[:, :3], 'native_root_rotations_mat': local[:, 0],
              'native_rot6d': local[..., :2].reshape(frames, 52, 6)}
    return {k: values[k].reshape((frames,) + dtypes[k][1]).astype(dtypes[k][0]) for k in keys}


def transform(arrays, start, end, turn_right_deg=0.0, offset_x_m=0.0, offset_z_m=0.0):
    """Trim to [start, end) and apply a rigid ground-plane transform."""
    if 'scene_spec_json' in arrays:
        raise ValueError('人体场景包含固定时间轴和物体坐标，当前拼接仅支持普通动作')
    frames = _frames(arrays)
    if type(start) is not int or type(end) is not int or not 0 <= start < end <= frames:
        raise ValueError('请选择有效的素材入点和出点')
    if end - start < LIMITS['min_clip_frames']:
        raise ValueError('每段素材至少保留 %d 帧' % LIMITS['min_clip_frames'])
    for value, bound in ((turn_right_deg, LIMITS['max_turn_input_deg']), (offset_x_m, LIMITS['max_offset_m']),
                         (offset_z_m, LIMITS['max_offset_m'])):
        if type(value) not in (int, float) or not np.isfinite(value) or abs(value) > bound:
            raise ValueError('旋转或平移参数超出范围')
    keys = _channels(arrays)
    out = {}
    for key, value in arrays.items():
        if key.startswith('kimodo_') and np.ndim(value) and np.shape(value)[0] == frames:
            continue  # raw generator evidence belongs to the source version only
        out[key] = value[start:end].copy() if key in keys else np.array(value, copy=True)
    yaw = _yaw(turn_right_deg)
    t = out['native_transl'].astype(np.float64)
    moved = (t - t[0]) @ yaw.T + t[0] + np.array([offset_x_m, 0.0, offset_z_m])
    local = _local(out)
    local[:, 0] = yaw @ local[:, 0]
    poses = Rotation.from_matrix(local[:, 0]).as_rotvec()
    count = end - start
    for key in keys:
        dtype = out[key].dtype
        if key in ('native_transl', 'smpl_trans'):
            out[key] = moved.astype(dtype)
        elif key == 'native_keypoints3d':
            out[key] = (out[key].astype(np.float64) @ yaw.T).astype(dtype)
        elif key == 'smpl_poses':
            shaped = out[key].reshape(count, 52, 3).copy(); shaped[:, 0] = poses
            out[key] = shaped.reshape(out[key].shape).astype(dtype)
        elif key == 'smpl_Rh':
            out[key] = poses.astype(dtype)
        elif key == 'native_root_rotations_mat':
            out[key] = local[:, 0].astype(dtype)
        elif key == 'native_rot6d':
            six = out[key].copy(); six[:, 0] = local[:, 0, :, :2].reshape(count, 6)
            out[key] = six.astype(dtype)
    if 'smpl_num_frames' in out:
        out['smpl_num_frames'] = np.array(count, dtype=out['smpl_num_frames'].dtype).reshape(out['smpl_num_frames'].shape)
    return out


def _root(arrays, f):
    return arrays['native_transl'][f].astype(np.float64)


def heading(arrays, f):
    points = arrays['native_keypoints3d'][f].astype(np.float64)
    across = points[L_HIP] - points[R_HIP]
    return float(np.arctan2(-across[2], across[0]))


def gap(a, b):
    p, q = _root(a, -1), _root(b, 0)
    turn = np.angle(np.exp(1j * (heading(b, 0) - heading(a, -1))))
    return {'distance_m': float(np.hypot(*(q - p)[[0, 2]])), 'turn_deg': float(abs(np.rad2deg(turn)))}


def check(a, b, frames):
    """Kinematic plausibility of the requested gap; not a dynamics guarantee."""
    if type(frames) is not int or not LIMITS['min_transition_frames'] <= frames <= LIMITS['max_transition_frames']:
        raise ValueError('过渡时长需在 %.1f–%.1f 秒之间' % (LIMITS['min_transition_frames'] / 30, LIMITS['max_transition_frames'] / 30))
    g = gap(a, b); seconds = frames / 30
    if g['distance_m'] / seconds > LIMITS['max_speed_m_s']:
        raise ValueError('两段间距 %.2f 米，过渡至少需要 %.1f 秒' % (g['distance_m'], g['distance_m'] / LIMITS['max_speed_m_s']))
    if g['turn_deg'] / seconds > LIMITS['max_turn_deg_s']:
        raise ValueError('转向 %.0f°过急，过渡至少需要 %.1f 秒' % (g['turn_deg'], g['turn_deg'] / LIMITS['max_turn_deg_s']))
    return dict(g, seconds=seconds, mean_speed_m_s=g['distance_m'] / seconds)


BODY_JOINTS = 22


def conform(arrays, rest, parents, tolerance=5e-3):
    """Re-derive joint positions from the unchanged rotations on the farm rig.

    Older library motions carry hand/finger positions from a different hand
    template; their 22 body joints already match. Kimodo composes and
    validates on the farm rig, so the joined motion must use it throughout.
    Rotations, root translation and body joints are unchanged; a clip whose
    body joints disagree with the rig is rejected rather than re-rigged.
    """
    from .kimodo_adapter import fk
    points, _ = fk(_local(arrays), rest, parents)
    k = arrays['native_keypoints3d'].astype(np.float64)
    points += (k[:, :1] - points[:, :1])
    shift = np.linalg.norm(points - k, axis=-1)
    if float(shift[:, :BODY_JOINTS].max()) > tolerance:
        raise ValueError('素材的身体骨架与拼接骨架不一致，无法拼接')
    out = dict(arrays)
    out['native_keypoints3d'] = points.astype(arrays['native_keypoints3d'].dtype)
    return out, {'hand_positions_rederived': bool(shift.max() > 0), 'max_hand_shift_m': float(shift.max()),
                 'body_shift_max_m': float(shift[:, :BODY_JOINTS].max())}


def join(a, b, frames, rest, parents):
    """A + placeholder gap + B, with every canonical channel kept consistent."""
    (a, rig_a), (b, rig_b) = conform(a, rest, parents), conform(b, rest, parents)
    keys = _channels(a)
    if keys != _channels(b) or {k for k in a if k in STATIC} != {k for k in b if k in STATIC}:
        raise ValueError('两段素材字段不一致，无法拼接')
    for key in STATIC - {'smpl_num_frames'}:
        if key in a and not np.array_equal(np.asarray(a[key]), np.asarray(b[key])):
            raise ValueError('两段素材的骨架或体型参数不同，无法拼接')
    report = check(a, b, frames)
    la, lb = _local(a)[-1], _local(b)[0]
    s = (np.arange(1, frames + 1) / (frames + 1))
    eased = s * s * (3 - 2 * s)
    local = np.empty((frames, 52, 3, 3))
    for j in range(52):
        local[:, j] = Slerp([0.0, 1.0], Rotation.from_matrix(np.stack((la[j], lb[j]))))(eased).as_matrix()
    # Cubic Hermite root path carrying each clip's own end/start velocity.
    p0, p1 = _root(a, -1), _root(b, 0)
    v0 = _root(a, -1) - _root(a, -2); v1 = _root(b, 1) - _root(b, 0)
    span = frames + 1
    h00, h10, h01, h11 = 2*s**3 - 3*s**2 + 1, s**3 - 2*s**2 + s, -2*s**3 + 3*s**2, s**3 - s**2
    transl = h00[:, None]*p0 + h10[:, None]*v0*span + h01[:, None]*p1 + h11[:, None]*v1*span
    dtypes = {k: (a[k].dtype, a[k].shape[1:]) for k in keys}
    middle = _fill(local, transl, keys, dtypes, rest, parents)
    out = {k: np.concatenate((a[k], middle[k], b[k])) for k in keys}
    for key in a:
        if key not in keys:
            out[key] = np.array(a[key], copy=True)
    total = _frames(a) + frames + _frames(b)
    if 'smpl_num_frames' in out:
        out['smpl_num_frames'] = np.array(total, dtype=out['smpl_num_frames'].dtype).reshape(out['smpl_num_frames'].shape)
    validate_motion(dict(out, rest_joints=rest, parents=parents))
    selection = {'start_frame': _frames(a), 'end_frame': _frames(a) + frames}
    report.update(version=VERSION, selection=selection, frames=total, rig_conformance=[rig_a, rig_b],
                  placeholder='hermite root path and slerped pose; regenerated by Kimodo before review')
    return out, report


def _next_action(text):
    """First sentence of B's English prompt, as a clause after 'the person'."""
    if not isinstance(text, str):
        return ''
    text = ' '.join(text.split())
    if not text or len(text) > 2000 or not all(' ' <= c <= '~' for c in text):
        return ''
    first = text.split('. ')[0].rstrip('.').strip()
    for prefix in ('A person ', 'a person ', 'The person ', 'the person ', 'Someone ', 'someone '):
        if first.startswith(prefix):
            first = first[len(prefix):]
            break
    words = first.split()
    return ' '.join(words[:40])


def walk_prompt(a, b, frames, next_text=None):
    """English instruction for the gap: walk to B's first-frame root, then go into B.

    Distance and direction are measured from A's last frame in A's own facing
    frame, so the words match what the user arranged in the top-down view.
    """
    p, q = _root(a, -1), _root(b, 0)
    ha, hb = heading(a, -1), heading(b, 0)
    dx, dz = q[0] - p[0], q[2] - p[2]
    forward = dx * np.sin(ha) + dz * np.cos(ha)
    right = -dx * np.cos(ha) + dz * np.sin(ha)
    distance = float(np.hypot(dx, dz))
    turn = float(np.rad2deg(np.angle(np.exp(1j * (hb - ha)))))  # positive = left
    bearing = float(np.rad2deg(np.arctan2(right, forward)))     # positive = right
    if abs(turn) < 15:
        facing = 'keeping roughly the same facing'
    else:
        facing = 'turning about %d degrees to the %s' % (int(round(abs(turn) / 15) * 15), 'left' if turn > 0 else 'right')
    if distance < 0.15:
        walk = 'A person takes a few natural steps almost in place, ' + facing
    else:
        sectors = ['forward', 'forward and to the right', 'to the right', 'back and to the right',
                   'back', 'back and to the left', 'to the left', 'forward and to the left']
        where = sectors[int(((bearing + 22.5) % 360) // 45)]
        walk = ('A person turns to face the destination initially %s, then walks naturally about %.1f meters forward, '
                'following a smooth curved path while facing the direction of travel, %s') % (where, distance, facing)
    # B's action is recorded but kept out of the text: naming it made Kimodo
    # perform it inside the gap and wander off the planned path.
    action = _next_action(next_text)
    text = (walk + ', with relaxed hip-width steps and arms swinging clear of the body, '
            'then stops at the target spot and stands still, ready to begin the next movement.')
    return text, {'distance_m': distance, 'bearing_right_deg': bearing, 'turn_left_deg': turn,
                  'seconds': frames / 30, 'next_action': action}


def validate_request(value):
    """Shape-only validation of a desktop splice request."""
    if not isinstance(value, dict) or set(value) - {'request_id', 'clips', 'transition_frames', 'seed'}:
        raise ValueError('拼接请求包含不支持的字段')
    clips = value.get('clips')
    if not isinstance(clips, list) or len(clips) != LIMITS['clips']:
        raise ValueError('拼接需要两段素材')
    for clip in clips:
        if not isinstance(clip, dict) or set(clip) != {'motion_id', 'start_frame', 'end_frame', 'transform'}:
            raise ValueError('素材参数不完整')
        t = clip['transform']
        if not isinstance(t, dict) or set(t) != {'turn_right_deg', 'offset_x_m', 'offset_z_m'}:
            raise ValueError('素材变换参数不完整')
    seed = value.get('seed', 0)
    if type(seed) is not int or not 0 <= seed < 2**32:
        raise ValueError('无效随机种子')
    return value
