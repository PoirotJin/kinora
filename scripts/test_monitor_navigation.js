const fs=require('fs'),vm=require('vm'),assert=require('assert');
const source=fs.readFileSync('web/review/app.js','utf8');
const html=fs.readFileSync('web/review/index.html','utf8');
const nodes=new Map();const $=id=>{if(!nodes.has(id))nodes.set(id,{id,hidden:true,setAttribute(k,v){this[k]=v;}});return nodes.get(id);};
const buttons=['home','review','gallery','storage','monitor','tasks'].map(id=>$('show-'+id));$('page-nav').querySelectorAll=()=>buttons;
let allowed=true,mon=0,tasks=0;const state={user:{role:'user'},session:1,saving:false,dirty:false,request:0};
const context=vm.createContext({state,$,leave:()=>allowed,closeRetarget(){},window:{},fillReview(){},refreshMonitor(){mon++;},refreshTasks(){tasks++;}});
vm.runInContext(source.slice(source.indexOf('function showOperations('),source.indexOf("$('show-monitor').onclick=()=>showOperations")),context);
