const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const source = fs.readFileSync(__dirname + '/../src/renderer/app.js', 'utf8');
const nodes = {};
const $ = id => nodes[id] ||= {value:'', checked:false, hidden:false, disabled:false, textContent:'', addEventListener(type, fn) {this[type] = fn;}};
const S = {session:1};
let saved = {username:'test-user', password:'synthetic-password'};
const desktop = {loadCredentials:async()=>saved, forgetCredentials:async()=>{saved=null;}};
const entered = [];
const messages = [];
const context = vm.createContext({$, S, window:{desktop}, enter:user=>entered.push(user.username),
  toast:message=>messages.push(message), cloud:async()=>({user:{username:'old-account'}})});
vm.runInContext(source.slice(source.indexOf('let credentialRevision'), source.indexOf("$('offline-retry').addEventListener")), context);
(async()=>{
 await context.restoreCredentials();
 assert.equal($('login-user').value, 'test-user');
 assert.equal($('login-pass').value, 'synthetic-password');
 assert.equal($('login-remember').checked,true);
 await $('login-forget').click();
 assert.equal(saved,null); assert.equal($('login-pass').value,'');
 let resolve;
 desktop.loadCredentials=()=>new Promise(r=>resolve=r);
 const pending=context.restoreCredentials();
 $('login-user').value='typed-user'; $('login-user').input();
 resolve({username:'saved-user',password:'saved-password'}); await pending;
 assert.equal($('login-user').value,'typed-user'); assert.equal($('login-pass').value,'');

 let deleteCalls = 0;
 desktop.forgetCredentials = () => {
   deleteCalls++;
   return new Promise(done => { resolve = done; });
 };
 $('login-remember').checked = true;
 const deletion = $('login-forget').click();
 assert.equal($('login-forget').disabled, true);
 assert.equal($('login-submit').disabled, true);
 assert.equal($('login-remember').checked, false, 'Deleting the saved login also turns off automatic saving');
 await $('login-forget').click();
 assert.equal(deleteCalls, 1, 'Only one deletion can run');
 $('login-user').value = 'newly-typed-user';
 $('login-pass').value = 'newly-typed-password';
 $('login-pass').input();
 $('login-remember').checked = true;
 $('login-remember').input();
 resolve();
 await deletion;
 assert.equal($('login-user').value, 'newly-typed-user');
 assert.equal($('login-pass').value, 'newly-typed-password');
 assert.equal($('login-remember').checked, true, 'Explicitly re-enabling the option is preserved');
 assert.equal($('login-submit').disabled, false);

 let reject;
 desktop.loadCredentials = () => new Promise((_, fail) => { reject = fail; });
 const staleRead = context.restoreCredentials();
 $('credential-status').textContent = 'newer status';
 $('login-pass').input();
 reject(new Error('late vault error'));
 await staleRead;
 assert.equal($('credential-status').textContent, 'newer status');
 desktop.loadCredentials=async()=>{throw new Error('locked');};
 await context.restoreCredentials();
 assert.match($('credential-status').textContent,/手动输入/);

 let vaultStarted = false;
 desktop.saveCredentials = () => new Promise((_, fail) => { vaultStarted = true; reject = fail; });
 $('login-user').value = 'old-account';
 $('login-pass').value = 'old-password';
 $('login-remember').checked = true;
 const signingIn = $('gate-login').submit({preventDefault() {}});
 await new Promise(resolve => setImmediate(resolve));
 assert.equal(vaultStarted, true);
 S.session++;
 $('login-user').value = 'new-account';
 $('login-pass').value = 'new-password';
 $('login-error').textContent = 'current-session-status';
 reject(new Error('Old vault disconnected'));
 await signingIn;
 assert.deepEqual(entered, [], 'An old login cannot enter the workspace after a reconnect');
 assert.deepEqual(messages, [], 'A stale vault error cannot notify the current session');
 assert.equal($('login-pass').value, 'new-password');
 assert.equal($('login-error').textContent, 'current-session-status');
 assert.equal($('login-submit').disabled, false);

 desktop.saveCredentials = async () => {};
 context.cloud = async () => ({user:{username:'new-account'}});
 await $('gate-login').submit({preventDefault() {}});
 assert.deepEqual(entered, ['new-account']);
 assert.equal($('login-pass').value, '');

 desktop.loadCredentials = () => new Promise(done => { resolve = done; });
 $('login-user').value = '';
 const oldRead = context.restoreCredentials();
 S.session++;
 resolve({username:'old-account', password:'old-password'});
 await oldRead;
 assert.equal($('login-user').value, '');
 assert.equal($('login-pass').value, '');

 desktop.forgetCredentials = () => new Promise(done => { resolve = done; });
 const oldDeletion = $('login-forget').click();
 S.session++;
 $('credential-status').textContent = 'current vault status';
 resolve();
 await oldDeletion;
 assert.equal($('credential-status').textContent, 'current vault status');
 assert.equal($('login-submit').disabled, false);
 console.log('PASS: credential fill, removal, vault errors, and stale login/read/delete handling');
})().catch(e=>{console.error(e);process.exitCode=1;});
