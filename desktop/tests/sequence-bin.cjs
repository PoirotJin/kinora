const fs = require('node:fs'), vm = require('node:vm'), assert = require('node:assert/strict');
const source = fs.readFileSync(__dirname + '/../src/renderer/sequence-editor.js', 'utf8');
const render = source.slice(source.indexOf('  function renderBin()'), source.indexOf('  function thumb('));
const nodes = {};
const $ = id => nodes[id] ??= { children: [], replaceChildren() { this.children = []; }, append(x) { this.children.push(x); } };
const h = (tag, props, ...children) => ({ tag, ...props, children, addEventListener() {} });
const src = { frames: 120, fps: 30 }, clip = { id: 'source-a', src }, result = { id: 'splice-result' };
const E = { bin: [{ id: 'source-a', src }, { id: 'source-b', src }], seq: { clips: [clip] }, result, showing: true };
let message = '';
let saves = 0;
const root = { Workspace: { saveWorkspaceDebounced() { saves++; } } };
vm.runInNewContext(render + ';renderBin();', { E, $, h, root, Sequence: { MAX_CLIPS: 2 }, note: s => message = s, requestAnimationFrame() {}, beginBinDrag() {} });
const removeFirst = () => $('bin-list').children[0].children[2].children[1].onclick();
removeFirst();
assert.deepEqual(E.bin.map(x => x.id), ['source-b']);
assert.equal(E.seq.clips[0], clip);
assert.equal(E.seq.clips[0].src, src);
assert.equal(E.result, result);
assert.equal(E.showing, true);
removeFirst();
assert.equal(E.bin.length, 0);
assert.equal($('bin-empty').hidden, false);
assert.equal($('bin-count').textContent, '');
assert.match(message, /已从素材箱移除/);
assert.equal(saves, 2);
console.log('PASS: removing used and unused bin entries preserves timeline sources and splice result');
